E1_CLAIM_RUBRIC = """あなたは CTI 文書の事実確認の担当です。2 つの出力 (X と Y) から主張を取り出し、それぞれが入力に裏付けられるかを判定します。

入力は 2 つの節に分けて示します。
- 「記事の節」: 書き手への指示と記事 (または台帳の判定と証拠記事)
- 「線の節」: 共有する指標から機械的に導いた候補の関係 (記事が裏付ける事実ではない)。出力によってはこの節を受け取っていない

手順:
1. 各出力から、確かめられる主張 (事実・数値・日付・帰属・事象どうしの関係) をすべて取り出す。1 つの主張は 1 つの事実。見出し・本文・箇条書きのすべてが対象。見通し・推測であることを明示した文 (「〜の可能性」「〜を確かめる必要」) と、書き手への指示の言い換えは取り出さない
2. 各主張の support を 1 つ選ぶ
   - 記事: 記事の節に裏付けがある
   - 線の節のみ: 記事の節には無く、線の節が述べる範囲に裏付けがある
   - 裏付け無し: 入力のどこにも無い・入力と矛盾する・入力より確度を上げている (例: 線の節が「同じアクター」とだけ述べる関係を同一キャンペーン・同一事象と書く)
3. misattributed: 主張に出典番号 ([n] など) が付いているが、その内容が線の節にしか無い場合 true

text は主張を 40 字以内に縮めて書く。"""

E1_CLAIM_QUESTION = "出力 X と出力 Y のそれぞれから主張を取り出し、上の手順で判定してください。"


class Claim(BaseModel):
    model_config = ConfigDict(extra="ignore")
    text: str
    support: Literal["記事", "線の節のみ", "裏付け無し"]
    misattributed: bool


class ClaimVerdict(BaseModel):
    model_config = ConfigDict(extra="ignore")
    claims_x: list[Claim] = Field(default_factory=list)
    claims_y: list[Claim] = Field(default_factory=list)


