E2_RUBRIC = """あなたは CTI の上級分析官です。2 つの事象 (それぞれ、1 つの事案についての報道の束) の材料を読み、両者の関係を判定します。材料は事象の見出し・期間・構成記事の題・媒体・要約です。システムが機械的に付けた「主題アクターの札」も示します (札は誤っていることがあります)。

## relation (1 つ選ぶ。複数に当てはまるときは上にあるものを選ぶ)
- 同じ事象: 同じ行為者 (または原因) による、同じ対象への、ひとまとまりの出来事。別媒体・別言語の報道や、同じ事案の第 n 報 (影響範囲・帰属・当局の警告・事後分析) を含む
- 系統: 別の事象だが同じ出来事の流れにある。脆弱性の修正・告知 ⇔ その悪用・KEV への追加、事案から派生した別の主体の出来事 (行政指導・処分・声明)、まとめ記事・一括の勧告とその中の 1 件 (包含)
- 同じアクターの別の活動: 同じ脅威アクター (同じ集団、その下位・別名) による、別の作戦・別の被害
- 無関係: 上のどれでもない。共有するのが一般的な語・国・業種・頻出の道具・報じた媒体だけの場合を含む

## same_attacker
両事象の攻撃主体 (行為者) は同じ脅威アクター (同じ集団・その下位・別名) か。はい / いいえ / 不明。どちらかの行為者が材料から特定できないときは 不明。

## tag_1 / tag_2 (事象 1 / 事象 2 の主題アクターの札)
- 正しい: 札のアクターが、その事象の行為者 (攻撃・作戦の主体) として報じられている
- 誤り: 札のアクターはその事象の行為者ではない (言及・比較・別の事案・被害者側・報じた側など)
- タグ無し: 札が空
- 判断できない: 材料から決められない
札が複数あるときは、1 つでも誤りがあれば 誤り。

reason は 150 字以内で、材料の事実だけを書く。"""

E2_QUESTION = "事象 1 と事象 2 の関係を上の定義で判定してください。"

Tag = Literal["正しい", "誤り", "タグ無し", "判断できない"]


class EdgeVerdict(BaseModel):
    model_config = ConfigDict(extra="ignore")
    relation: Literal["同じ事象", "系統", "同じアクターの別の活動", "無関係"]
    same_attacker: Literal["はい", "いいえ", "不明"]
    tag_1: Tag
    tag_2: Tag
    confidence: Literal["high", "low"]
    reason: str
