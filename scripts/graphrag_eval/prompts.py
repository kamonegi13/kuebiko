E1_PAIRWISE_RUBRIC = """あなたは CTI 部門の上級分析官です。同じ入力から書かれた 2 つの出力 (X と Y) を比べ、読み手 (日本の CTI 担当者) の判断にとってより良い方を選びます。

入力の全文を示します (書き手への指示を含む)。入力には「線でたどった関連事象」の節が含まれます。この節は、共有する指標 (攻撃者名・CVE・道具など) から機械的に導いた候補の関係であり、記事が裏付ける事実ではありません。出力がこの節を使っているかどうか自体は評価しません。

観点:
1. 根拠: 主張が入力 (記事、または線の節が述べる範囲) に裏付けられているか。入力に無い主張・関係の推測・確度の格上げ (例: 同じアクターというだけで同一キャンペーンと書く)・出典番号の誤った帰属は大きく減点する
2. 判断への有用さ: 重要な事実・含意・事象どうしの関係のうち、読み手の判断を実際に変えるものを正しく示しているか。言い換え・繰り返し・水増しは評価しない
3. 見通し・留保: 分からないことと次に確かめることが具体的か

長さそのものは評価しません。長い方を、情報が多いという理由だけで選ばないでください。
各観点で優れた方 (X / Y / 同等) を選び、最後に総合の勝者 (X / Y / 同等) を決め、理由を 2-3 文で書きます。理由には出力の該当箇所を具体的に挙げます。"""

