"""claim の重複照合に課す埋込の確認 (2026-09-22)。

``assignment.match_claim`` はキーの重なりで「この claim は既存の情勢と同じ」と判定する。
Opus の盲検ラベル 422 件で測ると、**繋いだもののうち正しいのは 14%** だった
(規則別の精度: 強アンカー 0% / 国 2+ かつ語 1+ 6% / 国 1+ かつ語 2+ 11% / 語のみ 3+ 15%)。
つまり大半が**誤った吸収**で、本来開設すべき追跡が既存の情勢に紛れて消えていた
(実例: 「対中半導体規制の MATCH 法」1 件が大手通信事業者のメール侵害・中国の SLBM 試験・
国内小売の侵害・通信会社の大規模流出を吸い込んでいた)。

⚠⚠ **代償の向きが detect の一覧絞りと逆**。一覧は落とすと二重開設を招くので回収を
優先したが、こちらは**誤って繋ぐ方が高くつく** (追跡が消える)。繋がなければ新規開設
されるだけで、後から統合もできる。よって精度を優先する。

実測 (claim は検出ログに先頭 50 字しか残っておらず、埋込に不利な条件):

| 閾値 | 同一を繋ぐ | 別事象も繋ぐ | 繋いだ中の正解率 |
|---|---|---|---|
| 現行 (確認なし) | 34/39 | 213/383 (56%) | 14% |
| 0.60 | 25/39 | 19/383 (5%) | 57% |
| **0.65** | **22/39** | **7/383 (2%)** | **76%** |
| 0.70 | 20/39 | 5/383 (1%) | 80% |
"""

from __future__ import annotations

import numpy as np

#: claim と情勢の題名の余弦の下限。AUC 0.918 の動作点で、誤った吸収を 97% 減らす。
#: 0.70 まで上げても正解率は 76% → 80% としか伸びず、同一の回収が 56% → 51% へ落ちる。
CLAIM_DUP_THRESHOLD = 0.65


def confirm_by_embedding(
    *,
    claim_vec: np.ndarray | None,
    situation_vec: np.ndarray | None,
    threshold: float = CLAIM_DUP_THRESHOLD,
) -> bool:
    """キーの重なりで繋いだ組を、意味的にも近いかで確認する (純粋関数)。

    ⚠ **埋込が作れないときは繋ぐ** (従来どおり)。関門の失敗で挙動を変えない —
    繋がない側へ倒すと、埋込の障害が静かに重複開設を量産する。
    """
    if claim_vec is None or situation_vec is None:
        return True
    return float(np.dot(claim_vec, situation_vec)) >= threshold
